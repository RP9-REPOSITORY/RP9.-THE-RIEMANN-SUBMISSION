def simple_reference_primes(limit: int) -> List[int]:
    if limit < 2:
        return []
    sieve = bytearray(b"\x01") * (limit + 1)
    sieve[0:2] = b"\x00\x00"
    root = isqrt(limit)
    for p in range(2, root + 1):
        if sieve[p]:
            start = p * p
            sieve[start:limit + 1:p] = b"\x00" * len(range(start, limit + 1, p))
    return [i for i in range(2, limit + 1) if sieve[i]]


def build_external_reference_segment(low: int, high: int, base_primes: List[int]) -> bytearray:
    """Independent conventional reference, created only after P.B.F. generation."""
    size = high - low + 1
    ref = bytearray(b"\x01") * size

    if low == 0:
        if size > 0:
            ref[0] = 0
        if size > 1:
            ref[1] = 0
    elif low == 1:
        ref[0] = 0

    root = isqrt(high)
    for p in base_primes:
        if p > root:
            break
        start = p * p
        if start < low:
            # External reference only: conventional segment alignment.
            start = ((low + p - 1) // p) * p
        if start <= high:
            local = start - low
            ref[local:size:p] = b"\x00" * len(range(local, size, p))

    return ref


