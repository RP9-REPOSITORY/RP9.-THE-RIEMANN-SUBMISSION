def build_csv(payload: Dict[str, object]) -> List[str]:
    lines = [
        "limit,observation_positions,pbf_new_closures,reproduced_positions,false_positives,false_negatives,exact_positional_match,elapsed_seconds,status"
    ]
    for r in payload["results"]:
        lines.append(
            ",".join([
                str(r["limit"]), str(r["observation_positions"]), str(r["pbf_new_closures"]),
                str(r["reproduced_positions"]), str(r["false_positives"]), str(r["false_negatives"]),
                str(r["exact_positional_match"]), str(r["elapsed_seconds"]), str(r["status"]),
            ])
        )
    return lines


def build_control_log(payload: Dict[str, object]) -> List[str]:
    s = payload["summary"]

    def shown(value: object, grouped: bool = False) -> str:
        if value is None:
            return "NOT_EXECUTED"
        if grouped and isinstance(value, int):
            return f"{value:,}"
        return str(value)

    lines = [
        "P.B.F. FULL POSITIONAL GENEALOGY — CONTROL LOG",
        "=" * 88,
        f"Python Code ID: {PYTHON_CODE_ID}",
        f"Official Code Title: {OFFICIAL_CODE_TITLE}",
        f"File: {FILE_NAME}",
        f"Version: {VERSION}",
        f"Timestamp: {payload['metadata']['generated_at']}",
        f"Global Status: {s['global_status']}",
        f"Maximum Executed Genealogy Status: {s['maximum_executed_genealogy_status']}",
        f"First Deviation Position: {s['first_deviation_position'] if s['first_deviation_position'] is not None else 'NONE'}",
        "",
        "SCALE BREAKDOWN",
        "-" * 88,
    ]
    for r in payload["results"]:
        lines += [
            f"LIMIT: {r['limit']:,}",
            f"  Observation positions: {r['observation_positions']:,}",
            f"  P.B.F. closures: {shown(r['pbf_new_closures'], grouped=True)}",
            f"  Reproduced positions: {shown(r['reproduced_positions'], grouped=True)}",
            f"  False positives: {shown(r['false_positives'])}",
            f"  False negatives: {shown(r['false_negatives'])}",
            f"  Exact positional match: {shown(r['exact_positional_match'])}",
            f"  Status: {r['status']}",
            "",
        ]
    return lines


def write_outputs(output_dir: Path, payload: Dict[str, object]) -> Dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "data_json": output_dir / DATA_FILE,
        "final_report": output_dir / FINAL_REPORT_FILE,
        "data_sheet": output_dir / DATA_SHEET_FILE,
        "csv": output_dir / CSV_FILE,
        "control_log": output_dir / CONTROL_FILE,
        "execution_log": output_dir / EXECUTION_FILE,
    }
    write_json(paths["data_json"], payload)
    write_text(paths["final_report"], build_report(payload))
    write_text(paths["data_sheet"], build_data_sheet(payload))
    write_text(paths["csv"], build_csv(payload))
    write_text(paths["control_log"], build_control_log(payload))
    write_text(paths["execution_log"], [
        "P.B.F. FULL POSITIONAL GENEALOGY — EXECUTION LOG",
        "=" * 88,
        f"Timestamp: {now_text()}",
        f"Python Code ID: {PYTHON_CODE_ID}",
        f"Official Code Title: {OFFICIAL_CODE_TITLE}",
        f"File: {FILE_NAME}",
        f"Version: {VERSION}",
        f"Maximum limit: {payload['metadata']['maximum_limit']:,}",
        f"Global status: {payload['summary']['global_status']}",
        f"Maximum executed genealogy status: {payload['summary']['maximum_executed_genealogy_status']}",
        f"Total execution: {payload['metadata']['total_execution_seconds']} s",
    ])
    return paths


