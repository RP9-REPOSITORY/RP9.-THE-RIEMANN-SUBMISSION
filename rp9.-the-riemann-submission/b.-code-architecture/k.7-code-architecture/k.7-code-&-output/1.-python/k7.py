def fill_locked_observation_segment(
    low: int,
    high: int,
    next_left: int,
    next_right: int,
) -> Tuple[bytearray, int, int, int]:
    """
    Build exactly the same locked observation field inside [low, high].

    next_left / next_right carry the next sequential 6-step endpoints across
    segment boundaries. No modulo classification is used.
    """
    size = high - low + 1
    field = bytearray(size)

    if low <= 2 <= high:
        field[2 - low] = 1
    if low <= 3 <= high:
        field[3 - low] = 1

    # center-1 stream: 5, 11, 17, ...
    if next_left < low:
        while next_left < low:
            next_left += 6
    if next_left <= high:
        start = next_left - low
        count = len(range(start, size, 6))
        field[start:size:6] = b"\x01" * count
        next_left += count * 6

    # center+1 stream: 7, 13, 19, ...
    if next_right < low:
        while next_right < low:
            next_right += 6
    if next_right <= high:
        start = next_right - low
        count = len(range(start, size, 6))
        field[start:size:6] = b"\x01" * count
        next_right += count * 6

    return field, int(sum(field)), next_left, next_right


def apply_genealogy_segment(
    field: bytearray,
    low: int,
    high: int,
    references: List[int],
    next_hits: List[int],
) -> None:
    """
    Continue every internally generated genealogy through this segment.

    Each genealogy starts at 2p and thereafter advances only by +p. Its next
    endpoint is persisted between segments. Slice clearing is only a storage
    optimization for the same sequential endpoint series.
    """
    size = len(field)

    for i, p in enumerate(references):
        x = next_hits[i]
        if x > high:
            continue

        # The prior segment leaves x at the first endpoint beyond its boundary,
        # so x is normally already >= low. The loop is a safety-preserving guard.
        while x < low:
            x += p

        if x > high:
            next_hits[i] = x
            continue

        local_start = x - low
        count = len(range(local_start, size, p))
        field[local_start:size:p] = b"\x00" * count
        next_hits[i] = x + count * p


