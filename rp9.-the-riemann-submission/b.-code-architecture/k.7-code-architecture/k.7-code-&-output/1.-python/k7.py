def build_locked_reference_field(limit: int) -> bytearray:
    field = bytearray(limit + 1)
    if limit >= 2:
        field[2] = 1
    if limit >= 3:
        field[3] = 1
    center = 6
    while center <= limit + 1:
        left = center - 1
        right = center + 1
        if 5 <= left <= limit:
            field[left] = 1
        if 5 <= right <= limit:
            field[right] = 1
        center += 6
    return field


def project_internal_genealogy(reference: int, limit: int, field: bytearray, hit: bytearray) -> None:
    x = reference + reference
    while x <= limit:
        if field[x]:
            hit[x] = 1
        x += reference


def generate_internal_references(limit: int) -> List[int]:
    """
    Generate all P.B.F. closures through `limit` with the original K7 mechanism.

    This is NOT an external prime list. It is generated internally from the same
    fixed field + sequential addition + coincidence rules used by the original
    benchmark.
    """
    field = build_locked_reference_field(limit)
    hit = bytearray(limit + 1)
    closures: List[int] = []

    for p in (2, 3):
        if p <= limit and field[p]:
            closures.append(p)
            project_internal_genealogy(p, limit, field, hit)

    position = 5
    while position <= limit:
        if field[position]:
            if not hit[position]:
                closures.append(position)
                project_internal_genealogy(position, limit, field, hit)
        position += 1

    return closures


