def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate the P.B.F. full positional genealogy through the stated domain."
    )
    parser.add_argument(
        "--limits", type=int, nargs="+", default=DEFAULT_SCALES,
        help="Mechanical milestones through the final 100B domain.",
    )
    parser.add_argument(
        "--segment-size", type=int, default=DEFAULT_SEGMENT_SIZE,
        help=f"Integer positions per memory segment. Default: {DEFAULT_SEGMENT_SIZE:,}.",
    )
    parser.add_argument("--output-dir", type=str, default=None)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    limits = sorted(set(args.limits))
    if max(limits) > MAXIMUM_SUPPORTED_LIMIT:
        raise ValueError(
            "Mechanical limits must not exceed the supported 100B domain."
        )

    root = base_dir()
    output_dir = (
        Path(args.output_dir).expanduser().resolve()
        if args.output_dir else root / OUTPUT_DIR_NAME
    )
    checkpoint_path = output_dir / CHECKPOINT_FILE

    try:
        # Create visible output immediately and record that execution started.
        output_dir.mkdir(parents=True, exist_ok=True)
        (output_dir / ERROR_FILE).unlink(missing_ok=True)
        write_text(output_dir / EXECUTION_FILE, [
            "P.B.F. FULL POSITIONAL GENEALOGY — LIVE EXECUTION LOG",
            "=" * 88,
            f"Started: {now_text()}",
            f"Python Code ID: {PYTHON_CODE_ID}",
            f"Official Code Title: {OFFICIAL_CODE_TITLE}",
            f"Version: {VERSION}",
            f"Execution milestone limits: {', '.join(f'{x:,}' for x in limits)}",
            "Status: RUNNING",
        ])
        payload = execute_full_genealogy(
            limits, args.segment_size, checkpoint_path=checkpoint_path
        )
        paths = write_outputs(output_dir, payload)
        checkpoint_path.unlink(missing_ok=True)
        print("=" * 96)
        print(f"GLOBAL STATUS              : {payload['summary']['global_status']}")
        print(f"MAXIMUM EXECUTED DOMAIN    : {payload['summary']['maximum_executed_genealogy_limit']:,}")
        print(f"POSITIONAL GENEALOGY       : {payload['summary']['maximum_executed_genealogy_status']}")
        first_deviation = payload["summary"]["first_deviation_position"]
        print(f"FIRST DEVIATION POSITION   : {first_deviation if first_deviation is not None else 'NONE'}")
        print(f"OUTPUT DIRECTORY           : {output_dir}")
        print("=" * 96)
        return 0 if payload["summary"]["global_status"] == "PASS" else 1
    except Exception as exc:
        output_dir.mkdir(parents=True, exist_ok=True)
        error_path = output_dir / ERROR_FILE
        write_text(error_path, [
            "P.B.F. FULL POSITIONAL GENEALOGY — ERROR LOG",
            "=" * 88,
            f"Timestamp: {now_text()}",
            f"Python Code ID: {PYTHON_CODE_ID}",
            f"Official Code Title: {OFFICIAL_CODE_TITLE}",
            f"Version: {VERSION}",
            f"Error type: {type(exc).__name__}",
            f"Error: {exc}",
            "",
            traceback.format_exc(),
        ])
        print(f"CRITICAL ERROR: {exc}")
        print(f"Error log: {error_path}")
        return 1


if __name__ == "__main__":
    exit_code = main()
    if os.name == "nt" and sys.stdin.isatty():
        try:
            input("Press Enter to close...")
        except EOFError:
            pass
    raise SystemExit(exit_code)
