def fixed_observation_count_exact(limit: int) -> int:
    """Exact cardinality of the locked field generated by 2, 3, then 6k±1."""
    if limit < 2:
        return 0
    count = 1
    if limit >= 3:
        count += 1
    if limit >= 5:
        count += (limit + 1) // 6
        count += max(0, (limit - 1) // 6)
    return count


